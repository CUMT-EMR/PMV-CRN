from __future__ import annotations
import argparse

def build_argparser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description='Optimized temporal-image CMR contrastive early-warning training')
    p.add_argument('--input-csv', type=str, default='classifier.csv', help='CSV with columns date, AE, EMR, GAS, LABEL')
    p.add_argument('--out-dir', type=str, default='optimized_cmr_outputs')
    p.add_argument('--device', type=str, default='')
    p.add_argument('--seed', type=int, default=2026)
    p.add_argument('--max-points', type=int, default=60000)
    p.add_argument('--window', type=int, default=256)
    p.add_argument('--horizon', type=int, default=0)
    p.add_argument('--label-mode', choices=['raw', 'future_any'], default='raw')
    p.add_argument('--img-size', type=int, default=32)
    p.add_argument('--image-map-type', choices=['precursor9', 'texture9', 'hybrid9', 'sensor_gaf_mtf9', 'sensor_trajectory9', 'precursor6', 'precursor4'], default='precursor9')
    p.add_argument('--train-ratio', type=float, default=0.6)
    p.add_argument('--val-ratio', type=float, default=0.2)
    p.add_argument('--split-mode', choices=['event', 'random_stratified', 'blocked_random_stratified'], default='random_stratified')
    p.add_argument('--block-size', type=int, default=1024)
    p.add_argument('--max-normal-segment-len', type=int, default=1024)
    p.add_argument('--purge-windows', type=int, default=1)
    p.add_argument('--sample-stride', type=int, default=1)
    p.add_argument('--keep-all-positive-train', action='store_true')
    p.add_argument('--negative-train-stride', type=int, default=1)
    p.add_argument('--use-absolute-ts', action='store_true', default=True)
    p.add_argument('--no-absolute-ts', dest='use_absolute_ts', action='store_false')
    p.add_argument('--balance-mode', choices=['none', 'sampler', 'weight', 'both'], default='sampler')
    p.add_argument('--sampler-positive-ratio', type=float, default=0.12)
    p.add_argument('--max-class-weight', type=float, default=3.0)
    p.add_argument('--batch-size', type=int, default=256)
    p.add_argument('--num-workers', type=int, default=0)
    p.add_argument('--cache-dataset', action=argparse.BooleanOptionalAction, default=True)
    p.add_argument('--pin-memory', action=argparse.BooleanOptionalAction, default=True)
    p.add_argument('--prefetch-factor', type=int, default=4)
    p.add_argument('--epochs', type=int, default=120)
    p.add_argument('--early-stop-patience', type=int, default=25)
    p.add_argument('--lr', type=float, default=0.001)
    p.add_argument('--min-lr', type=float, default=1e-05)
    p.add_argument('--lr-factor', type=float, default=0.5)
    p.add_argument('--lr-patience', type=int, default=25)
    p.add_argument('--weight-decay', type=float, default=0.0001)
    p.add_argument('--grad-clip', type=float, default=1.0)
    p.add_argument('--d-model', type=int, default=96)
    p.add_argument('--n-heads', type=int, default=4)
    p.add_argument('--ts-rules', type=int, default=8)
    p.add_argument('--img-rules', type=int, default=8)
    p.add_argument('--dropout', type=float, default=0.15)
    p.add_argument('--concept-prior-blend', type=float, default=0.15)
    p.add_argument('--model-mode', choices=['full', 'temporal_only', 'image_only', 'no_gate_fusion', 'fixed_weight_fusion', 'no_image_branch', 'no_stat_features', 'sensor_image', 'sensor_image_only'], default='full', help='Ablation mode used to test branch/stat/rule contributions.')
    p.add_argument('--fixed-temporal-weight', type=float, default=0.7)
    p.add_argument('--loss-type', choices=['ce', 'focal'], default='ce')
    p.add_argument('--focal-alpha', type=float, default=0.75)
    p.add_argument('--focal-gamma', type=float, default=2.0)
    p.add_argument('--lambda-aux', type=float, default=0.1)
    p.add_argument('--lambda-contrast', type=float, default=0.0)
    p.add_argument('--contrast-warmup-epochs', type=int, default=10)
    p.add_argument('--lambda-rule-consistency', type=float, default=0.02)
    p.add_argument('--lambda-concept', type=float, default=0.0)
    p.add_argument('--lambda-rule-sparse', type=float, default=0.001)
    p.add_argument('--lambda-proto', type=float, default=0.0)
    p.add_argument('--lambda-img-aux', type=float, default=0.0)
    p.add_argument('--lambda-image-metric', type=float, default=0.0)
    p.add_argument('--lambda-image-proto', type=float, default=0.0)
    p.add_argument('--lambda-image-view-diversity', type=float, default=0.0)
    p.add_argument('--lambda-img-rate', type=float, default=0.0)
    p.add_argument('--lambda-gate-balance', type=float, default=0.0)
    p.add_argument('--gate-target-image-share', type=float, default=0.35)
    p.add_argument('--metric-temperature', type=float, default=0.2)
    p.add_argument('--smooth-window', type=int, default=1)
    p.add_argument('--embedding-max-points', type=int, default=5000)
    p.add_argument('--threshold-min', type=float, default=0.001)
    p.add_argument('--threshold-max', type=float, default=0.95)
    p.add_argument('--threshold-min-precision', type=float, default=0.0)
    p.add_argument('--auto-search', action='store_true')
    p.add_argument('--target-metric', type=float, default=0.9)
    return p
